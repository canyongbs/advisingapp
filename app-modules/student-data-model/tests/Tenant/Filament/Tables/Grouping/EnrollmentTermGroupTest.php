use AdvisingApp\StudentDataModel\Filament\Tables\Grouping\EnrollmentTermGroup;
use AdvisingApp\StudentDataModel\Models\Enrollment;
use AdvisingApp\StudentDataModel\Models\Term;
use Illuminate\Support\Str;

// The `id` is generated by the database unless given, so it is set here to keep it on the returned model.
$createEnrollment = fn (array $attributes): Enrollment => Enrollment::factory()->create([
    'id' => (string) Str::uuid(),
    'sis_term_id' => null,
    'semester_name' => null,
    ...$attributes,
]);

it('orders enrollments by term, most recent first, with unassigned enrollments last', function () use ($createEnrollment): void {
    $olderTerm = Term::factory()->create(['start_date' => '2020-09-01']);
    $recentTerm = Term::factory()->create(['start_date' => '2021-09-01']);
    $lowerOrderedTerm = Term::factory()->withoutSisTermId()->create(['name' => 'Summer 2012', 'order' => 1]);
    $higherOrderedTerm = Term::factory()->withoutSisTermId()->create(['name' => 'Fall 2012', 'order' => 2]);

    $unassignedEnrollment = $createEnrollment(['semester_name' => 'Unmatched']);
    $lowerOrderedEnrollment = $createEnrollment(['semester_name' => $lowerOrderedTerm->name]);
    $olderEnrollment = $createEnrollment(['sis_term_id' => $olderTerm->sis_term_id]);
    $higherOrderedEnrollment = $createEnrollment(['semester_name' => $higherOrderedTerm->name]);
    $recentEnrollment = $createEnrollment(['sis_term_id' => $recentTerm->sis_term_id]);

    $enrollments = EnrollmentTermGroup::make()->orderQuery(Enrollment::query(), 'asc')->get();

    expect($enrollments->modelKeys())->toBe([
        $recentEnrollment->getKey(),
        $olderEnrollment->getKey(),
        $higherOrderedEnrollment->getKey(),
        $lowerOrderedEnrollment->getKey(),
        $unassignedEnrollment->getKey(),
    ]);
});

it('titles the group with the display name of the term', function () use ($createEnrollment): void {
    $term = Term::factory()->create(['name' => 'FA-20', 'start_date' => '2020-09-01']);

    $enrollment = $createEnrollment(['sis_term_id' => $term->sis_term_id]);

    expect(EnrollmentTermGroup::make()->getTitle($enrollment))->toBe('FA-20 (Sep 2020)');
});

it('titles the group `Unassigned` when the enrollment has no term', function () use ($createEnrollment): void {
    $enrollment = $createEnrollment(['semester_name' => 'Unmatched']);

    expect(EnrollmentTermGroup::make()->getTitle($enrollment))->toBe('Unassigned');
});
