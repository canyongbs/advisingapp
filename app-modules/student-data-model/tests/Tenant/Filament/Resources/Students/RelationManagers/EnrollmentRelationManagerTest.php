use function Tests\asSuperAdmin;

it('can filter by name search', function (): void {
    asSuperAdmin();

    $regularEnrollment = Enrollment::factory()->state([
        'name' => 'Regular Course Name',
    ]);

    $searchableEnrollment = Enrollment::factory()->state([
        'name' => 'Unique Course Name',
    ]);

    $student = Student::factory()
        ->has($regularEnrollment, 'enrollments')
        ->has($searchableEnrollment, 'enrollments')
        ->create();

    Livewire::test(EnrollmentsRelationManager::class, [
        'ownerRecord' => $student,
        'pageClass' => ViewStudent::class,
    ])
        ->assertCanSeeTableRecords($student->enrollments)
        ->searchTable('Unique')
        ->assertCanSeeTableRecords([$student->enrollments->where('name', 'Unique Course Name')->first()])
        ->assertCanNotSeeTableRecords([$student->enrollments->where('name', 'Regular Course Name')->first()]);
});

describe('sis term id', function (): void {
    beforeEach(function (): void {
        asSuperAdmin();

        $studentConfigurationSettings = app(ManageStudentConfigurationSettings::class);
        $studentConfigurationSettings->is_enabled = true;
        $studentConfigurationSettings->save();
    });

    it('can create an enrollment with a `sis_term_id`', function (): void {
        $student = Student::factory()->create();

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->callAction(TestAction::make(CreateAction::class)->table(), [
                'sis_term_id' => '267',
            ])
            ->assertHasNoFormErrors();

        expect($student->enrollments()->sole()->sis_term_id)->toBe('267');
    });

    it('shows the `sis_term_id` when viewing an enrollment', function (): void {
        $student = Student::factory()->has(Enrollment::factory(['sis_term_id' => '267']), 'enrollments')->create();

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->mountAction(TestAction::make(ViewAction::class)->table($student->enrollments->sole()))
            ->assertSchemaComponentVisible('sis_term_id');
    });
});

describe('terms', function (): void {
    beforeEach(function (): void {
        asSuperAdmin();
    });

    // The `id` is generated by the database unless given, so it is set here to keep it on the returned model.
    $createEnrollment = fn (Student $student, array $attributes): Enrollment => Enrollment::factory()->create([
        'id' => (string) Str::uuid(),
        'sisid' => $student->sisid,
        'sis_term_id' => null,
        'semester_name' => null,
        ...$attributes,
    ]);

    it('lists enrollments grouped by term, most recent first, with unassigned enrollments last', function () use ($createEnrollment): void {
        $student = Student::factory()->create();

        $olderTerm = Term::factory()->create(['start_date' => '2020-09-01']);
        $recentTerm = Term::factory()->create(['start_date' => '2021-09-01']);

        $unassignedEnrollment = $createEnrollment($student, ['semester_name' => 'Unmatched']);
        $olderEnrollment = $createEnrollment($student, ['sis_term_id' => $olderTerm->sis_term_id]);
        $recentEnrollment = $createEnrollment($student, ['sis_term_id' => $recentTerm->sis_term_id]);

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->assertCanSeeTableRecords([$recentEnrollment, $olderEnrollment, $unassignedEnrollment], inOrder: true);
    });

    it('can filter by term', function () use ($createEnrollment): void {
        $student = Student::factory()->create();

        $term = Term::factory()->create();
        $otherTerm = Term::factory()->create();

        $enrollment = $createEnrollment($student, ['sis_term_id' => $term->sis_term_id]);
        $otherEnrollment = $createEnrollment($student, ['sis_term_id' => $otherTerm->sis_term_id]);
        $unassignedEnrollment = $createEnrollment($student, ['semester_name' => 'Unmatched']);

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->filterTable('term', [$term->getKey()])
            ->assertCanSeeTableRecords([$enrollment])
            ->assertCanNotSeeTableRecords([$otherEnrollment, $unassignedEnrollment]);
    });

    it('can filter by unassigned enrollments alongside a term', function () use ($createEnrollment): void {
        $student = Student::factory()->create();

        $term = Term::factory()->create();
        $otherTerm = Term::factory()->create();

        $enrollment = $createEnrollment($student, ['sis_term_id' => $term->sis_term_id]);
        $otherEnrollment = $createEnrollment($student, ['sis_term_id' => $otherTerm->sis_term_id]);
        $unassignedEnrollment = $createEnrollment($student, ['semester_name' => 'Unmatched']);

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->filterTable('term', [EnrollmentTermFilter::UNASSIGNED])
            ->assertCanSeeTableRecords([$unassignedEnrollment])
            ->assertCanNotSeeTableRecords([$enrollment, $otherEnrollment])
            ->filterTable('term', [$term->getKey(), EnrollmentTermFilter::UNASSIGNED])
            ->assertCanSeeTableRecords([$enrollment, $unassignedEnrollment])
            ->assertCanNotSeeTableRecords([$otherEnrollment]);
    });

    it('offers the terms of the student enrollments, most recent first, and `Unassigned` as term filter options', function () use ($createEnrollment): void {
        $student = Student::factory()->create();

        $olderTerm = Term::factory()->create(['name' => 'FA-20', 'start_date' => '2020-09-01']);
        $recentTerm = Term::factory()->create(['name' => 'FA-21', 'start_date' => '2021-09-01']);
        $otherStudentTerm = Term::factory()->create();

        $createEnrollment($student, ['sis_term_id' => $olderTerm->sis_term_id]);
        $createEnrollment($student, ['sis_term_id' => $recentTerm->sis_term_id]);
        $createEnrollment(Student::factory()->create(), ['sis_term_id' => $otherStudentTerm->sis_term_id]);

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->assertTableFilterExists('term', fn (SelectFilter $filter): bool => $filter->getOptions() === [
                $recentTerm->getKey() => 'FA-21 (Sep 2021)',
                $olderTerm->getKey() => 'FA-20 (Sep 2020)',
                EnrollmentTermFilter::UNASSIGNED => 'Unassigned',
            ]);
    });

    it('shows the matched term in place of the semester name when viewing an enrollment', function () use ($createEnrollment): void {
        $student = Student::factory()->create();

        $term = Term::factory()->create(['name' => 'FA-20', 'start_date' => '2020-09-01']);

        $enrollment = $createEnrollment($student, ['sis_term_id' => $term->sis_term_id, 'semester_name' => 'Fall 2020']);

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->mountAction(TestAction::make(ViewAction::class)->table($enrollment))
            ->assertSchemaComponentExists('semester_name', checkComponentUsing: fn (TextEntry $entry): bool => $entry->getState() === 'FA-20 (Sep 2020)');
    });

    it('shows the semester name when viewing an enrollment without a matched term', function () use ($createEnrollment): void {
        $student = Student::factory()->create();

        $enrollment = $createEnrollment($student, ['semester_name' => 'Fall 2020']);

        Livewire::test(EnrollmentsRelationManager::class, [
            'ownerRecord' => $student,
            'pageClass' => ViewStudent::class,
        ])
            ->mountAction(TestAction::make(ViewAction::class)->table($enrollment))
            ->assertSchemaComponentExists('semester_name', checkComponentUsing: fn (TextEntry $entry): bool => $entry->getState() === 'Fall 2020');
    });

    describe('when the `TermsConsolidationFeature` is inactive', function () use ($createEnrollment): void {
        beforeEach(function (): void {
            TermsConsolidationFeature::deactivate();
        });

        it('lists enrollments grouped by semester name', function () use ($createEnrollment): void {
            $student = Student::factory()->create();

            $springEnrollment = $createEnrollment($student, ['semester_name' => 'Spring 2021']);
            $fallEnrollment = $createEnrollment($student, ['semester_name' => 'Fall 2020']);

            Livewire::test(EnrollmentsRelationManager::class, [
                'ownerRecord' => $student,
                'pageClass' => ViewStudent::class,
            ])
                ->assertCanSeeTableRecords([$fallEnrollment, $springEnrollment], inOrder: true);
        });

        it('shows the semester name rather than the matched term when viewing an enrollment', function () use ($createEnrollment): void {
            $student = Student::factory()->create();

            $term = Term::factory()->create(['name' => 'FA-20', 'start_date' => '2020-09-01']);

            $enrollment = $createEnrollment($student, ['sis_term_id' => $term->sis_term_id, 'semester_name' => 'Fall 2020']);

            Livewire::test(EnrollmentsRelationManager::class, [
                'ownerRecord' => $student,
                'pageClass' => ViewStudent::class,
            ])
                ->mountAction(TestAction::make(ViewAction::class)->table($enrollment))
                ->assertSchemaComponentExists('semester_name', checkComponentUsing: fn (TextEntry $entry): bool => $entry->getState() === 'Fall 2020');
        });
    });
});
